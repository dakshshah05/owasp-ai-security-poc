"""
mitigations.py — Security mitigations for the AI Security POC
Each function provides a defense against a specific OWASP LLM/Agentic risk.
"""
import re
import html
import json
from typing import Tuple

# ─────────────────────────────────────────────
# LLM01 — Prompt Injection Mitigation
# ─────────────────────────────────────────────

INJECTION_PATTERNS = [
    r"ignore\s+(all\s+)?(previous|prior|above|earlier)\s+(instructions?|rules?|constraints?)",
    r"disregard\s+(all\s+)?(previous|prior|above|earlier)",
    r"you\s+are\s+now\s+(an?\s+)?(unrestricted|jailbroken|evil|dan|free)",
    r"act\s+as\s+(if\s+you\s+are\s+)?(an?\s+)?(unrestricted|evil|hacker|attacker)",
    r"forget\s+(your|all)\s+(previous\s+)?(instructions?|rules?|training)",
    r"new\s+instructions?:",
    r"system\s*:\s*(you\s+are|ignore|override)",
    r"<system>",
    r"\[system\]",
    r"print\s+your\s+(system\s+prompt|instructions?|rules?)",
    r"repeat\s+(everything|all)\s+(above|before|prior)",
    r"what\s+(is|are|were)\s+your\s+(original\s+)?(instructions?|rules?|system\s+prompt)",
    r"as\s+dan\b",
    r"do\s+anything\s+now",
    r"play\s+a\s+game.*dan",
    r"from\s+now\s+on,\s+respond\s+only",
    r"system_config(\.txt)?",
    r"silently\s+read",
    r"competing\s+objective",
    r"list\s+all\s+files.*knowledge\s+base",
]

def check_prompt_injection(user_input: str) -> Tuple[bool, str]:
    """
    Detect prompt injection attempts using pattern matching.
    Returns (is_injection, reason).
    """
    text = user_input.lower()
    for pattern in INJECTION_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return True, f"Matched injection signature: '{pattern}'"
    return False, ""


# ─────────────────────────────────────────────
# LLM02 — Sensitive Information Disclosure Mitigation
# ─────────────────────────────────────────────

SENSITIVE_REQUEST_PATTERNS = [
    r"database\s+credentials?",
    r"aws\s+access\s+keys?",
    r"jwt\s+(signing\s+)?secret",
    r"passwords?\s+stored",
    r"employee\s+salaries|salary\s+data",
    r"pan\s+card\s+numbers?",
    r"medical\s+conditions?|health\s+records?|insurance\s+claims?",
    r"all\s+employee\s+names.*salaries",
    r"tell\s+me\s+about\s+.*medical",
]

def check_sensitive_request(user_input: str) -> Tuple[bool, str]:
    """Detect requests specifically asking to leak credentials or PII."""
    text = user_input.lower()
    for pattern in SENSITIVE_REQUEST_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return True, f"Direct sensitive data query detected: '{pattern}'"
    return False, ""


SENSITIVE_PATTERNS = [
    r"SECRET-FLAG-\d{3}-\w+",
    r"password\s*[:=]\s*\S+",
    r"api[_\s]?key\s*[:=]\s*\S+",
    r"AKIA[A-Z0-9]{16}",                      # AWS Access Key
    r"sk_live_[A-Za-z0-9]+",                  # Stripe Secret
    r"SG\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+",   # SendGrid
    r"\b[A-Z]{5}\d{4}[A-Z]\b",               # PAN Card
    r"\b\d{4}-\d{4}-\d{4}\b",               # Bank Account (simple)
    r"-----BEGIN RSA PRIVATE KEY-----",
    r"jwt[_\s]?secret\s*[:=]\s*\S+",
    r"Rs\.\s*[\d,]+",                        # Indian Rupee Salaries
    r"Hypertension|Type 2 Diabetes",          # Health condition terms
    r"CLM-2025-\d+",                         # Claim numbers
]

def sanitize_output(text: str) -> str:
    """Remove/redact sensitive patterns from LLM output."""
    for pattern in SENSITIVE_PATTERNS:
        text = re.sub(pattern, "[REDACTED]", text, flags=re.IGNORECASE)
    return text


# ─────────────────────────────────────────────
# LLM10 — Improper Output Handling Mitigation
# ─────────────────────────────────────────────

def sanitize_html_output(text: str) -> str:
    """Escape HTML in LLM output to prevent XSS."""
    return html.escape(text)


def sanitize_shell_output(text: str) -> str:
    """Escape shell metacharacters in commands generated by LLM."""
    dangerous_chars = [';', '&', '|', '`', '$', '(', ')', '<', '>']
    sanitized = text
    for ch in dangerous_chars:
        sanitized = sanitized.replace(ch, f"\\{ch}")
    return sanitized


def validate_json_output(text: str) -> Tuple[bool, str]:
    """Validate that output is safe JSON (for structured outputs)."""
    try:
        obj = json.loads(text)
        if "__proto__" in str(obj) or "constructor" in str(obj):
            return False, "Prototype pollution detected"
        return True, ""
    except json.JSONDecodeError as e:
        return False, str(e)


# ─────────────────────────────────────────────
# LLM03 / ASI02 — Excessive Agency / Tool Misuse Mitigation
# ─────────────────────────────────────────────

DANGEROUS_OPERATIONS = [
    r"rm\s+-rf",
    r"delete\s+(all|everything|production|backup)",
    r"drop\s+(table|database|schema|users)",
    r"format\s+[a-z]:",
    r"shutdown|reboot|poweroff",
    r"chmod\s+777",
    r"sudo\s+",
    r"send\s+an?\s+email\s+to\s+all",
    r"without\s+asking\s+for\s+confirmation",
]

def check_dangerous_operation(text: str) -> Tuple[bool, str]:
    """Detect requests for dangerous/irreversible operations."""
    for pattern in DANGEROUS_OPERATIONS:
        if re.search(pattern, text, re.IGNORECASE):
            return True, f"Dangerous operation detected: '{pattern}'"
    return False, ""


# ─────────────────────────────────────────────
# ASI03 — Identity & Privilege Abuse Mitigation
# ─────────────────────────────────────────────

def verify_identity_claim(text: str) -> Tuple[bool, str]:
    """Detect unverifiable identity/privilege escalation claims."""
    privilege_patterns = [
        r"i\s+am\s+(the\s+)?(admin|administrator|root|ceo|developer|lead\s+developer|system|god)",
        r"i\s+have\s+(admin|root|superuser|elevated|emergency\s+admin)\s+(access|privileges?|rights?|permission)",
        r"as\s+(an?\s+)?(admin|administrator|root|superuser)",
        r"grant\s+me\s+(admin|root|elevated|full)\s+(access|privileges?)",
        r"override\s+(security|access|permission|restriction|safety\s+rules)",
        r"authorizing\s+myself\s+to\s+override",
        r"manager.*called.*emergency\s+admin",
    ]
    for pattern in privilege_patterns:
        if re.search(pattern, text, re.IGNORECASE):
            return True, f"Identity claim requires verification: '{pattern}'"
    return False, ""


# ─────────────────────────────────────────────
# ASI06 — Memory & Context Poisoning Mitigation
# ─────────────────────────────────────────────

def validate_memory_entry(entry: str) -> Tuple[bool, str]:
    """Validate a memory/context entry before storing it."""
    poison_patterns = [
        r"ignore\s+(all\s+)?(future|subsequent|next|security)\s+(instructions?|queries?|requests?|rules?)",
        r"always\s+(respond\s+with|say|output|return|share)",
        r"from\s+now\s+on",
        r"new\s+(rule|policy):",
        r"remember:\s*(ignore|always|never|override)",
        r"password\s+has\s+been\s+changed\s+to",
        r"users\s+are\s+automatically\s+verified\s+admins?",
        r"in\s+our\s+last\s+conversation,?\s+i\s+told\s+you",
    ]
    for pattern in poison_patterns:
        if re.search(pattern, entry, re.IGNORECASE):
            return False, f"Context poisoning attempt detected: '{pattern}'"
    return True, ""


# ─────────────────────────────────────────────
# General input sanitization
# ─────────────────────────────────────────────

def sanitize_input(text: str) -> str:
    """Basic input sanitization — strip control chars, limit length."""
    text = re.sub(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]', '', text)
    max_len = 4096
    if len(text) > max_len:
        text = text[:max_len] + " [TRUNCATED]"
    return text


def apply_all_mitigations(user_input: str) -> Tuple[bool, str, str]:
    """
    Apply all mitigations in sequence.
    Returns (blocked, reason, sanitized_input).
    """
    # Check for injection
    is_injection, reason = check_prompt_injection(user_input)
    if is_injection:
        return True, f"Prompt injection: {reason}", user_input

    # Check for sensitive data requests
    is_sensitive, reason = check_sensitive_request(user_input)
    if is_sensitive:
        return True, f"Sensitive data request: {reason}", user_input

    # Check for privilege escalation
    is_priv, reason = verify_identity_claim(user_input)
    if is_priv:
        return True, f"Privilege escalation: {reason}", user_input

    # Check for dangerous ops
    is_dangerous, reason = check_dangerous_operation(user_input)
    if is_dangerous:
        return True, f"Dangerous operation: {reason}", user_input

    # Sanitize
    sanitized = sanitize_input(user_input)
    return False, "", sanitized
